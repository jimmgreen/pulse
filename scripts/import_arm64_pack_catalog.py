"""Import four published ARM64 pack manifests; never invent hashes or run tools.

Release assets are immutable inputs. SHA-256 and byte size must agree with the
GitHub asset metadata before a complete native catalog replaces the output.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

SYMBOLS = {'ffmpeg': 'Media', 'images': 'Image', 'raw': 'Raw', 'archive': 'Archive'}
TOOLS = {'ffmpeg': 'ffmpeg.exe', 'images': 'pulse-imgpack.exe', 'raw': 'pulse-rawpack.exe', 'archive': '7z.exe'}
MAX_FILE = 256 * 1024 * 1024


def require(ok, message):
    if not ok:
        raise ValueError(message)


def fetch(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'Pulse-native-pack-catalog', 'Accept': 'application/vnd.github+json'})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def validate_manifest(key, version, manifest, assets):
    require(manifest.get('id') == key and manifest.get('version') == version and
            manifest.get('architecture') == 'arm64', f'Wrong pack identity/architecture: {key}')
    files = manifest.get('files')
    require(isinstance(files, list) and 0 < len(files) < 128, f'Invalid file count: {key}')
    names = set()
    for item in files:
        name = item.get('name', '')
        require(isinstance(name, str) and re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*', name) and
                name not in names, f'Unsafe/duplicate installed name: {key}')
        names.add(name)
        packed = item.get('packed', {})
        require(packed.get('name') == name + '.lzms', f'Unexpected asset name: {key}/{name}')
        for entry in (item, packed):
            require(type(entry.get('size')) is int and 0 < entry['size'] <= MAX_FILE and
                    isinstance(entry.get('sha256'), str) and re.fullmatch(r'[a-f0-9]{64}', entry['sha256']),
                    f'Invalid pinned size/hash: {key}/{name}')
        asset = assets.get(packed['name'])
        require(asset and asset.get('size') == packed['size'] and
                asset.get('digest') == 'sha256:' + packed['sha256'], f'Remote payload metadata differs: {key}/{name}')
    require(TOOLS[key] in names, f'Missing native helper: {key}')
    return files


def render_pack(key, version, repository, files):
    prefix = f'k{SYMBOLS[key]}PackArm64'
    base = f'https://github.com/{repository}/releases/download/pack-{key}-{version}-arm64/'
    lines = [f'inline constexpr PackFile {prefix}Files[] = {{']
    for item in sorted(files, key=lambda item: item['name']):
        packed = item['packed']
        lines.append(f'    {{L"{item["name"]}", {item["size"]}, L"{item["sha256"]}", '
                     f'{packed["size"]}, L"{packed["sha256"]}"}},')
    lines += ['};', f'inline constexpr PackRelease {prefix}Release{{L"{key}", L"{version}", L"{base}",',
              f'    {prefix}Files, std::size({prefix}Files)}};', '']
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repository', required=True)
    for key in SYMBOLS:
        parser.add_argument(f'--{key}-version', required=True)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/app/pack_catalog_arm64_generated.h')
    args = parser.parse_args()
    require(re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', args.repository), 'Invalid repository')
    lines = ['// Generated by scripts/import_arm64_pack_catalog.py from published ARM64 manifests.', '#pragma once', '']
    for key in SYMBOLS:
        version = getattr(args, key + '_version')
        require(re.fullmatch(r'\d+(?:\.\d+)+', version), 'Use a numeric dotted pack version')
        tag = f'pack-{key}-{version}-arm64'
        release = json.loads(fetch(f'https://api.github.com/repos/{args.repository}/releases/tags/{tag}'))
        require(not release.get('draft') and release.get('tag_name') == tag, f'Unpublished/wrong release: {tag}')
        assets = {item['name']: item for item in release['assets']}
        name = f'pulse-pack-{key}-{version}-arm64.json'
        require(name in assets, f'Missing manifest: {tag}')
        asset = assets[name]
        base = f'https://github.com/{args.repository}/releases/download/{tag}/'
        require(asset['browser_download_url'] == base + name, 'Unexpected manifest origin')
        payload = fetch(asset['browser_download_url'])
        require(len(payload) == asset['size'] and 'sha256:' + hashlib.sha256(payload).hexdigest() == asset.get('digest'),
                f'Manifest size/hash mismatch: {tag}')
        files = validate_manifest(key, version, json.loads(payload), assets)
        lines += render_pack(key, version, args.repository, files)
        print(f'{key}: verified published ARM64 manifest and {len(files)} payload digests at {tag}')
    # Nothing is written unless all four published manifests and payload metadata pass.
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Wrote complete ARM64 catalog: {args.output}')


if __name__ == '__main__':
    main()
