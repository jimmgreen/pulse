"""Stage one native pack with hash-pinned LZMS assets; never upload anything."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct

from package_preview_packs import Lzms, MAX_FILE, SYMBOLS, TOOLS, require


def check_machine(data, architecture, name):
    require(len(data) >= 64 and data[:2] == b'MZ', f'Invalid PE: {name}')
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    require(64 <= pe <= len(data) - 6 and data[pe:pe + 4] == b'PE\0\0', f'Invalid PE header: {name}')
    machine = struct.unpack_from('<H', data, pe + 4)[0]
    require(machine == {'x64': 0x8664, 'arm64': 0xAA64}[architecture], f'Wrong {architecture} machine: {name}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--id', required=True, choices=SYMBOLS)
    parser.add_argument('--architecture', required=True, choices=('x64', 'arm64'))
    parser.add_argument('--version', required=True)
    parser.add_argument('--tag', required=True)
    parser.add_argument('--repository', required=True)
    parser.add_argument('--pack-directory', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    for value in (args.version, args.tag):
        require(re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*', value), 'Invalid release tag/version')
    require(re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', args.repository), 'Invalid repository')
    require((args.pack_directory / TOOLS[args.id]).is_file(), 'Missing main tool')
    args.output.mkdir(parents=True, exist_ok=True)
    prefix = f'k{SYMBOLS[args.id]}Pack' + ('Arm64' if args.architecture == 'arm64' else '')
    array, release = prefix + 'Files', prefix + 'Release'
    base = f'https://github.com/{args.repository}/releases/download/{args.tag}/'
    lines = [f'// {args.id} {args.version} {args.architecture}; generated by package_single_preview_pack.py',
             f'inline constexpr PackFile {array}[] = {{']
    files = []
    codec = Lzms()
    for path in sorted(args.pack_directory.iterdir()):
        require(path.is_file() and re.fullmatch(r'[A-Za-z0-9_.-]+', path.name), f'Unexpected pack entry: {path.name}')
        data = path.read_bytes()
        require(0 < len(data) <= MAX_FILE, f'Invalid file size: {path.name}')
        if path.suffix.lower() in ('.exe', '.dll'):
            check_machine(data, args.architecture, path.name)
        packed = codec.pack(data)
        name = path.name + '.lzms'
        (args.output / name).write_bytes(packed)
        sha = hashlib.sha256(data).hexdigest()
        packed_sha = hashlib.sha256(packed).hexdigest()
        files.append(dict(name=path.name, size=len(data), sha256=sha,
                          packed=dict(name=name, size=len(packed), sha256=packed_sha)))
        lines.append(f'    {{L"{path.name}", {len(data)}, L"{sha}", {len(packed)}, L"{packed_sha}"}},')
    lines += ['};', f'inline constexpr PackRelease {release}{{L"{args.id}", L"{args.version}", L"{base}",',
              f'    {array}, sizeof({array}) / sizeof({array}[0])}};']
    suffix = '-arm64' if args.architecture == 'arm64' else ''
    catalog = args.output / f'pack-catalog{suffix}.inc'
    catalog.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    manifest = dict(id=args.id, version=args.version, architecture=args.architecture,
                    repository=args.repository, release_tag=args.tag, files=files)
    (args.output / f'pulse-pack-{args.id}-{args.version}{suffix}.json').write_text(
        json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(f'{args.id}: verified {len(files)} {args.architecture} files and LZMS round trips; catalog={catalog}')


if __name__ == '__main__':
    main()
