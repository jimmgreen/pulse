"""Generate native package discovery and manifest authoring contracts."""
import argparse
import json
from pathlib import Path
import template_catalog
import contract_compat

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "schemas/extensions/manifest.schema.json"
HEADER = ROOT / "src/app/extensions/manifest_schema.generated.h"
TYPES = ROOT / "sdk/typescript/manifest.generated.d.ts"
API_HEADER = ROOT / "src/app/extensions/api_description.generated.h"
API_TYPES = ROOT / "sdk/typescript/api.generated.d.ts"
TEMPLATE_HEADER = ROOT / "src/app/extensions/templates.generated.h"


def read_json(path):
    def unique(items):
        result = {}
        for key, value in items:
            if key in result:
                raise ValueError("Duplicate JSON key: " + key)
            result[key] = value
        return result
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique,
                      parse_constant=lambda value: (_ for _ in ()).throw(ValueError("Invalid JSON constant: " + value)))



def describe(schema, metadata=None):
    description = {
        "apiVersion": 1, "manifestSchema": schema,
        "limits": {"manifestBytes": 65536, "idBytes": 64, "labelBytes": 128},
        "capabilities": [], "bindings": [],
        "templates": list(template_catalog.names()),
        "developerFeatures": ["nativePackages"],
        "developmentNotes": ["Native DLL packages require installation review and explicit enablement. Resource declarations are installation disclosures, not per-call permission gates. Metadata validation does not load or execute a DLL."],
        "nativeSdk": {"abiVersion": 1, "status": "developer-preview",
                      "trust": "trusted-in-process-not-sandboxed", "catalogPath": "sdk/native/api-catalog.json",
                      "catalog": read_json(ROOT / "sdk/native/api-catalog.json")},
    }
    description["contractIdentity"] = contract_compat.identity(description)
    return description


def cpp_string(symbol, value, delimiter):
    text = json.dumps(value, ensure_ascii=True, separators=(",", ":"))
    if ')' + delimiter + '"' in text:
        raise ValueError("Generated JSON conflicts with C++ raw-string delimiter")
    return ('// Generated by tools/extensions/generate_sdk.py. Do not edit.\n#pragma once\n'
            '#include <string_view>\nnamespace pulse::extensions::generated {\n'
            'inline constexpr std::string_view ' + symbol + ' =\n' +\
            '\n'.join('R"' + delimiter + '(' + text[i:i+8000] + ')' + delimiter + '"' for i in range(0, len(text), 8000)) + ';\n}\n')


def generate(schema, metadata=None):
    if set(schema["properties"]) != {"apiVersion", "id", "name", "resources", "native"}:
        raise ValueError("Unexpected native manifest fields")
    templates = template_catalog.all_templates()
    for template in templates.values():
        if set(template) - set(schema["properties"]):
            raise ValueError("Native template contains removed or unknown fields")
    header = cpp_string("kTemplates", templates, "pulse_templates")
    header += '#include <array>\nnamespace pulse::extensions::generated {\ninline constexpr std::array<const char*, ' + str(len(templates)) + '> kTemplateNames = {' + ', '.join(json.dumps(name) for name in templates) + '};\n}\n'
    declarations = ' | '.join(json.dumps(value) for value in schema["properties"]["resources"]["items"]["enum"])
    types = '// Generated by tools/extensions/generate_sdk.py. Do not edit.\n'
    types += 'export type ResourceDeclaration = ' + declarations + ';\n'
    types += 'export interface NativePackage { version: 1; architecture: "windows-x64"; library: string; sha256: string; files?: { path: string; sha256: string }[] }\n'
    types += 'export interface ExtensionManifest { apiVersion: 1; id: string; name: string; resources?: ResourceDeclaration[]; native?: NativePackage }\n'
    api_types = '// Generated by tools/extensions/generate_sdk.py. Do not edit.\nexport interface ExtensionApiDescription { apiVersion: 1; manifestSchema: object; limits: Record<string, number>; capabilities: []; bindings: []; templates: string[]; developerFeatures: string[]; developmentNotes: string[]; contractIdentity: { formatVersion: 1; algorithm: "sha256"; canonicalization: "sorted-ascii-json-v1"; scope: "discovery-excluding-contractIdentity"; sha256: string }; nativeSdk: { abiVersion: 1; status: "developer-preview"; trust: "trusted-in-process-not-sandboxed"; catalogPath: string; catalog: object } }\n'
    return {HEADER: cpp_string("kManifestSchema", schema, "pulse_schema"),
            API_HEADER: cpp_string("kApiDescription", describe(schema), "pulse_api"),
            TYPES: types, API_TYPES: api_types, TEMPLATE_HEADER: header}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generate(read_json(SCHEMA))
    stale = []
    for path, expected in outputs.items():
        if path.is_file() and path.read_text(encoding="utf-8") == expected:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            with path.open("w", encoding="utf-8", newline="\n") as stream:
                stream.write(expected)
    if stale:
        parser.exit(1, "Generated extension contracts are stale: " + ", ".join(stale) + "\n")
    print("Extension contracts are current" if args.check else "Generated extension contracts")


if __name__ == "__main__":
    main()
