// Diagnostic: pulse_preview_test --probe <file> [pixels] [out.bmp]
// Prints what the Word readers see in <file> and what the preview host returns
// for a grid thumbnail request, and saves that bitmap. Read-only on <file>.
static int RunProbe(const std::wstring& file, uint32_t pixels, const wchar_t* bmp_path) {
    const auto utf8 = [](const std::wstring& text) {
        const int n = WideCharToMultiByte(CP_UTF8, 0, text.data(), static_cast<int>(text.size()), nullptr, 0,
                                          nullptr, nullptr);
        std::string out(static_cast<size_t>((std::max)(n, 0)), '\0');
        if (n > 0) WideCharToMultiByte(CP_UTF8, 0, text.data(), static_cast<int>(text.size()), out.data(), n,
                                       nullptr, nullptr);
        return out;
    };
    const auto format = preview::SniffWordFile(file);
    std::printf("sniff=%d\n", static_cast<int>(format));
    preview::DocModel model;
    std::wstring error;
    const ULONGLONG model_start = GetTickCount64();
    const bool ok = preview::ReadWordModel(file, model, &error);
    std::printf("model ok=%d error=%s ms=%llu page=%.1fx%.1f margins l%.1f r%.1f t%.1f blocks=%zu\n", ok ? 1 : 0,
                utf8(error).c_str(), GetTickCount64() - model_start, model.page_width, model.page_height,
                model.margin_left, model.margin_right, model.margin_top, model.blocks.size());
    for (size_t i = 0; i < model.blocks.size() && i < 12; ++i) {
        const auto& b = model.blocks[i];
        if (b.table) {
            std::printf("  [%zu] table rows=%zu first=", i, b.rows.size());
            if (!b.rows.empty())
                for (const auto& cell : b.rows[0]) std::printf("|%s", utf8(cell.substr(0, 12)).c_str());
            std::printf("\n");
        } else {
            std::printf("  [%zu] %.1fpt%s align=%d %s\n", i, b.points, b.bold ? " bold" : "",
                        static_cast<int>(b.align), utf8(b.text.substr(0, 40)).c_str());
        }
    }
    Host host;
    if (!host.Start()) { std::printf("host start failed\n"); return 2; }
    Result result;
    const ULONGLONG start = GetTickCount64();
    const bool received = host.Request(file, result, MAXDWORD, pixels, ipc::PreviewRequestKind::Content,
                                       ipc::kPreviewRequestFlagGrid);
    std::printf("host received=%d ms=%llu kind=%d status=%d size=%ux%u error=%s\n", received ? 1 : 0,
                GetTickCount64() - start, static_cast<int>(result.response.kind), result.response.status,
                result.response.width, result.response.height, utf8(result.error).c_str());
    if (bmp_path && !result.pixels.empty()) {
        const uint32_t w = result.response.width, h = result.response.height;
        std::vector<unsigned char> out(54, 0);
        const uint32_t image = w * h * 4, total = 54 + image;
        const int32_t negative = -static_cast<int32_t>(h);
        out[0] = 'B'; out[1] = 'M';
        std::memcpy(&out[2], &total, 4);
        out[10] = 54; out[14] = 40;
        std::memcpy(&out[18], &w, 4);
        std::memcpy(&out[22], &negative, 4);
        out[26] = 1; out[28] = 32;
        std::memcpy(&out[34], &image, 4);
        for (uint32_t y = 0; y < h; ++y) {
            const unsigned char* row = result.pixels.data() + static_cast<size_t>(y) * result.response.stride;
            out.insert(out.end(), row, row + static_cast<size_t>(w) * 4);
        }
        std::printf("bmp written=%d\n", WriteBytes(bmp_path, out) ? 1 : 0);
    }
    return received ? 0 : 1;
}

