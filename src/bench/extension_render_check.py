"""Check PNGs from pulse_extension_render_test (requires Pillow).

Usage: python src/bench/extension_render_check.py build/extension-fixed-100 ...
Each prefix names the .png and .cached.png files generated by the test.
The left column uses the production extension renderer; the other columns
are controls. Compare suffix pixels after removing only integer translation.
"""
import sys
from PIL import Image


def verify(prefix):
    image = Image.open(prefix + ".png").convert("RGB")
    cached = Image.open(prefix + ".cached.png").convert("RGB")
    assert image.size == cached.size and image.tobytes() == cached.tobytes(), "cache changed pixels"
    background = image.getpixel((0, 0))
    suffixes = []
    for row in range(24):
        top = 10 + row * 35
        columns = [any(max(abs(a - b) for a, b in zip(image.getpixel((x, y)), background)) > 40
                       for y in range(top, top + 32)) for x in range(10, 320)]
        # Compare the final two glyphs, including their gap. All supported test
        # extensions end with two separate Latin glyphs at these font sizes.
        runs = []
        for x, occupied in enumerate(columns):
            if occupied and (x == 0 or not columns[x - 1]):
                runs.append([x, x])
            elif occupied:
                runs[-1][1] = x
        assert len(runs) >= 2, "missing suffix glyphs"
        left, right = runs[-2][0] + 10, runs[-1][1] + 11
        crop = image.crop((left, top, right, top + 32))
        suffixes.append((crop.size, crop.tobytes()))
    assert len(set(suffixes)) == 1, "suffix pixels depend on filename prefix"
    print(f"[PASS] {prefix}: 24 identical suffix rasters; cache unchanged")


if len(sys.argv) < 2:
    raise SystemExit("usage: extension_render_check.py <render-output-prefix> [...]")

for argument in sys.argv[1:]:
    verify(argument)
